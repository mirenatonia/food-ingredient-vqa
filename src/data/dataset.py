"""PyTorch dataset for image-level multi-label ingredient classification."""

from __future__ import annotations

from pathlib import Path
from typing import List, Optional

import numpy as np
import pandas as pd
import torch
from datasets import load_dataset
from PIL import Image
from torch.utils.data import Dataset
from torchvision import transforms

from src.utils.labels import get_num_classes


def parse_label_indices(label_string: str) -> List[int]:
    """Parse a space-separated list of FoodSeg103 class ids."""
    if not isinstance(label_string, str) or not label_string.strip():
        return []
    return [int(token) for token in label_string.split()]


def label_indices_to_multi_hot(label_indices: List[int], num_classes: int) -> torch.Tensor:
    """Convert FoodSeg103 class ids into a torch multi-hot target vector."""
    target = torch.zeros(num_classes, dtype=torch.float32)
    for class_id in label_indices:
        if class_id <= 0:
            continue
        class_index = class_id - 1
        if 0 <= class_index < num_classes:
            target[class_index] = 1.0
    return target


def parse_multi_hot(multi_hot_string: object, num_classes: int) -> torch.Tensor:
    """Parse a space-separated multi-hot vector stored in the processed CSV."""
    if isinstance(multi_hot_string, str) and multi_hot_string.strip():
        values = [float(token) for token in multi_hot_string.split()]
        if len(values) != num_classes:
            raise ValueError(
                f"Expected multi_hot vector of length {num_classes}, got {len(values)}."
            )
        return torch.tensor(values, dtype=torch.float32)

    if pd.isna(multi_hot_string):
        return torch.zeros(num_classes, dtype=torch.float32)

    raise ValueError(f"Unsupported multi_hot value: {multi_hot_string!r}")


class IngredientDataset(Dataset):
    """
    Dataset for training and evaluating a multi-label ingredient classifier.

    Rows come from the processed CSV files generated by build_multilabel_index.py.
    """

    def __init__(
        self,
        csv_path: str | Path,
        transform=None,
        hf_dataset_name: Optional[str] = None,
    ) -> None:
        self.csv_path = Path(csv_path)
        self.dataframe = pd.read_csv(self.csv_path)
        self.transform = transform
        self.hf_dataset_name = hf_dataset_name
        self.num_classes = get_num_classes()
        self._hf_cache = {}

    def __len__(self) -> int:
        return len(self.dataframe)

    def _load_huggingface_split(self, split_name: str):
        if split_name not in self._hf_cache:
            if self.hf_dataset_name is None:
                raise ValueError(
                    "This CSV references Hugging Face samples, but hf_dataset_name was not provided."
                )
            self._hf_cache[split_name] = load_dataset(self.hf_dataset_name, split=split_name)
        return self._hf_cache[split_name]

    def _load_image(self, row: pd.Series) -> Image.Image:
        image_path = row.get("image_path", "")
        source = row.get("source", "local")

        if isinstance(image_path, str) and image_path.strip():
            return Image.open(image_path).convert("RGB")

        if source == "huggingface":
            csv_split = str(row.get("split", "train"))
            hf_split = "validation" if csv_split in {"val", "test"} else csv_split
            hf_split_dataset = self._load_huggingface_split(hf_split)

            hf_row_idx = row.get("hf_row_idx", row.get("sample_id"))
            if pd.isna(hf_row_idx):
                raise ValueError(f"Missing hf_row_idx for Hugging Face row: {row.to_dict()}")
            hf_row_idx = int(hf_row_idx)

            sample = hf_split_dataset[int(hf_row_idx)]
            image = sample["image"]
            if not isinstance(image, Image.Image):
                image = Image.fromarray(np.array(image))
            return image.convert("RGB")

        raise FileNotFoundError(
            f"Could not resolve an image for row from {self.csv_path}: {row.to_dict()}"
        )

    def __getitem__(self, index: int):
        row = self.dataframe.iloc[index]
        image = self._load_image(row)
        multi_hot_value = row.get("multi_hot")
        if isinstance(multi_hot_value, str) and multi_hot_value.strip():
            target = parse_multi_hot(multi_hot_value, self.num_classes)
        else:
            label_indices = parse_label_indices(str(row.get("label_indices", "")))
            target = label_indices_to_multi_hot(label_indices, self.num_classes)

        if self.transform is not None:
            image = self.transform(image)
        else:
            image = transforms.ToTensor()(image)

        return {
            "image": image,
            "target": target,
            "sample_id": row.get("sample_id"),
        }
